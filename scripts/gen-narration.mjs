// Generates narration mp3s (Edge neural TTS, free) + word-boundary timings.
// Output: public/narr-XX.mp3 + remotion/narration.gen.ts
import { MsEdgeTTS, OUTPUT_FORMAT } from "msedge-tts";
import { writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";

const VOICE = "en-US-AndrewMultilingualNeural";
const FORMAT = OUTPUT_FORMAT.AUDIO_24KHZ_48KBITRATE_MONO_MP3;
const FPS = 30;

// id, scene local start frame, max slot frames, text
const LINES = [
  { id: "s1", at: 15, slot: 420, text: "Meet ArchFlow — an infinite canvas that turns a rambling voice memo into a real cloud architecture. No drag and drop. You just talk." },
  { id: "s2", at: 60, slot: 370, text: "We replaced PRD templates with prose. Your best ideas happen while talking — so we built a canvas that listens." },
  { id: "s3voice", at: 10, slot: 280, text: "Focus. Hold the Wispr hotkey, and describe the system raw — the way engineers actually think." },
  { id: "s3build", at: 25, slot: 500, text: "Three seconds after you stop speaking, the structured output engine materializes nodes, edges, regions — a real architecture, streaming onto the canvas." },
  { id: "s4prd", at: 25, slot: 440, text: "Then it writes the full PRD live, in a staff engineer's voice — spelling, passivity, weak verbs, audited before you ship." },
  { id: "demoA", at: 20, slot: 280, text: "This is not a mockup — twenty eight seconds of the real product, untouched." },
  { id: "demoB", at: 480, slot: 330, text: "Voice in. Architecture out. The PRD, written while you watch." },
  { id: "s5", at: 25, slot: 700, text: "Now the closer — a voice patch engine. Swap the Postgres for Spanner, front it with Memorystore, add a dead letter queue. The engine re-emits the entire canvas, and staff review passes before anything settles." },
  { id: "s6", at: 25, slot: 470, text: "Every change hands you synced Terraform, so the diagram and the infrastructure never drift." },
  { id: "s7", at: 25, slot: 530, text: "Under the hood — a validation first agent pipeline: every utterance through schema validation, canonical maps, and an undoable state machine." },
  { id: "s8", at: 20, slot: 450, text: "ArchFlow. Talk your stack into existence." },
];

const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&apos;");

const narrationDir = path.resolve("public");
mkdirSync(narrationDir, { recursive: true });

const out = [];
let i = 0;
for (const line of LINES) {
  const tts = new MsEdgeTTS();
  await tts.setMetadata(VOICE, FORMAT, { wordBoundaryEnabled: true });
  const { audioStream, metadataStream } = await tts.toStream(esc(line.text));

  const chunks = [];
  const words = [];
  let metaPending = "";
  const onData = (d) => {
    const buf = Buffer.isBuffer(d) ? d : Buffer.from(d);
    chunks.push(buf);
  };
  const onMeta = (d) => {
    metaPending += Buffer.isBuffer(d) ? d.toString("utf8") : String(d);
    while (metaPending.trim()) {
      let obj;
      try { obj = JSON.parse(metaPending); } catch { break; }
      metaPending = "";
      const entries = Array.isArray(obj.Metadata) ? obj.Metadata : [obj];
      for (const e of entries) {
        if (e?.Type === "WordBoundary" && e?.Data) {
          const s = e.Data.Offset / 1e7;
          const w = e.Data.Duration / 1e7;
          const text = e.Data.text?.Text ?? e.Data.Text ?? "";
          if (text) words.push({ w: text, s: +s.toFixed(3), e: +(s + w).toFixed(3) });
        }
      }
    }
  };
  metadataStream.on("data", onMeta);
  audioStream.on("data", onData);
  await new Promise((ok, bad) => { audioStream.on("close", ok); audioStream.on("error", bad); });

  const buf = Buffer.concat(chunks);
  if (buf.length < 2000) throw new Error(`line ${line.id}: suspiciously small audio (${buf.length} bytes)`);
  const file = `narr-${line.id}.mp3`;
  writeFileSync(path.join(narrationDir, file), buf);
  const bytesDur = (buf.length * 8) / 48000; // 48kbps
  const audioDur = words.length ? words[words.length - 1].e + 0.12 : bytesDur;
  const durF = Math.round(audioDur * FPS);
  const status = durF <= line.slot ? "ok" : "OVER-SLOT";
  console.log(`${line.id}: ${buf.length}B ~${audioDur.toFixed(1)}s (${durF}f / slot ${line.slot}f) ${status}, ${words.length} words`);
  out.push({ id: line.id, file, text: line.text, at: line.at, durF, words: words.map((x) => [x.w, x.s, x.e]) });
  i++;
}

const ts = `// AUTO-GENERATED by scripts/gen-narration.mjs — do not edit.
export type NarLine = { id: string; file: string; text: string; at: number; durF: number; words: Array<[string, number, number]> };
export const NARRATION: NarLine[] = ${JSON.stringify(out, null, 2).replace(/"(\w+)":/g, "$1:")};
`;
writeFileSync("remotion/narration.gen.ts", ts);
console.log(`\n wrote remotion/narration.gen.ts (${out.length} lines)`);
process.exit(0);
